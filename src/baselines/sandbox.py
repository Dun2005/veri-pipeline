"""
Execution Sandbox for Validating Counterexamples.
Grounded in CRITIC (Gou et al., ICLR 2024: Tool-Interactive Self-Correction).

Validates whether a counterexample generated by the LLM Judge actually
causes the program to diverge from the candidate explanation in reality.
"""

import ast
import inspect
from typing import Any, Dict, Optional, Tuple


def execute_counterexample(
    code: str,
    input_str: Optional[str],
    timeout_secs: float = 2.0
) -> Tuple[bool, Optional[str], Optional[str]]:
    """
    Executes the Python code with the concrete counterexample input.

    :param code: Source code of the program.
    :param input_str: Input assignments (e.g. 'x = 1, y = 1' or 'nums = []').
    :return: (success_executed, actual_runtime_result_or_error, details)
    """
    if not input_str or not input_str.strip():
        return False, None, "No counterexample input string provided."

    # Parse code to find target function name
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        return False, None, f"Code syntax error: {e}"

    fn_name = None
    fn_args = []
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            fn_name = node.name
            fn_args = [a.arg for a in node.args.args]
            break

    if not fn_name:
        return False, None, "No top-level function found in code."

    # Execute code in clean namespace to get callable function
    code_env: Dict[str, Any] = {}
    try:
        exec(code, code_env)
        target_fn = code_env.get(fn_name)
        if not callable(target_fn):
            return False, None, f"Object '{fn_name}' is not callable."
    except Exception as e:
        return False, None, f"Failed to compile code: {e}"

    # Parse input string assignments
    args_env: Dict[str, Any] = {}
    # Split by comma or newline
    statements = []
    for part in input_str.split("\n"):
        for sub in part.split(","):
            sub = sub.strip()
            if sub and "=" in sub:
                statements.append(sub)

    cleaned_input_script = "\n".join(statements)
    try:
        exec(cleaned_input_script, {"__builtins__": __builtins__}, args_env)
    except Exception as e:
        return False, None, f"Failed to parse counterexample assignment '{input_str}': {e}"

    # Map arguments to function call
    call_kwargs = {}
    for arg in fn_args:
        if arg in args_env:
            call_kwargs[arg] = args_env[arg]
        else:
            # Missing an argument
            return False, None, f"Counterexample does not specify argument '{arg}'."

    # Execute target function
    try:
        runtime_res = target_fn(**call_kwargs)
        actual_str = repr(runtime_res)
        return True, actual_str, f"Code successfully executed and returned {actual_str}."
    except Exception as e:
        err_str = f"{type(e).__name__}: {e}"
        return True, err_str, f"Code raised runtime exception: {err_str}."


def generate_boundary_traces(code: str, max_traces: int = 6) -> str:
    """
    Automatically samples boundary and edge-case inputs in a safe sandbox
    to provide the LLM Judge with empirical operational ground truth.
    Grounded in Program-Aided Language Models (PAL, ICML 2023).
    """
    try:
        tree = ast.parse(code)
    except Exception:
        return ""

    fn_name = None
    fn_args = []
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            fn_name = node.name
            fn_args = [a.arg for a in node.args.args]
            break

    if not fn_name or not fn_args:
        return ""

    code_env: Dict[str, Any] = {}
    try:
        exec(code, code_env)
        target_fn = code_env.get(fn_name)
        if not callable(target_fn):
            return ""
    except Exception:
        return ""

    # Synthesize boundary candidates based on arg count and types
    candidate_inputs = []
    if len(fn_args) == 1:
        arg = fn_args[0]
        if "num" in arg or "list" in arg or "arr" in arg:
            candidate_inputs = [[], [0], [1, 2, 3], [-2, 4], [-1, -3]]
        else:
            candidate_inputs = [0, 1, 2, -1, 4]
    elif len(fn_args) == 2:
        a1, a2 = fn_args[0], fn_args[1]
        if "arr" in a1 or "list" in a1:
            candidate_inputs = [([1, 2, 3], 2), ([1, 2, 3], 5), ([], 0), ([3, 1, 2], 2)]
        else:
            candidate_inputs = [(0, 0), (1, 0), (1, 1), (2, 1), (2, 3), (-1, -1)]

    traces = []
    for item in candidate_inputs:
        if len(traces) >= max_traces:
            break
        try:
            if isinstance(item, tuple):
                res = target_fn(*item)
                call_repr = f"{fn_name}({', '.join(repr(x) for x in item)})"
            else:
                res = target_fn(item)
                call_repr = f"{fn_name}({repr(item)})"
            traces.append(f"  • {call_repr} ==> {repr(res)}")
        except Exception as e:
            if isinstance(item, tuple):
                call_repr = f"{fn_name}({', '.join(repr(x) for x in item)})"
            else:
                call_repr = f"{fn_name}({repr(item)})"
            traces.append(f"  • {call_repr} ==> [Raised {type(e).__name__}: {e}]")

    if not traces:
        return ""

    return (
        "### Empirical Sandbox Execution Traces (Ground-Truth Execution on Sample Inputs):\n"
        + "\n".join(traces)
        + "\n"
    )


